#!/usr/bin/env python3
"""templates.py — deterministic prompt assembly for Prompt Forge (wq#957).

Each generated prompt is a fixed sequence of sections. Sections marked LIVE are
filled from fleet_context.py at generation time; sections marked STATIC are
maintained here as text (they change by PR, with review — still deterministic);
the single LLM section is passed in by the caller and clearly labeled in the
output so a reader can tell measured fact from model framing.

Categories (design: "each category loads a different template"):
    project      build/RE work on a thing
    research     deep research, evidence-graded output
    fleet-maint  changes to the fleet itself
    audit        read-only verification passes
    other        bootstrap + identity only, no category rules

Filter flags add rule sections (hardware, external-device gates, web research,
continuation, sensitive-content separation).
"""

from __future__ import annotations

import time

import fleet_context

CATEGORIES = ("project", "research", "fleet-maint", "audit", "other")

FILTERS = {
    "hardware": "Hardware project (adds hardware safety + backup rules)",
    "external_devices": "Involves external devices (adds tiered intelligence gates)",
    "web_research": "Needs web research",
    "continuation": "Continuation of an existing project (pulls prior fleet context)",
    "sensitive": "Sensitive content (adds orchestrator-separation guidance)",
}

# ---------------------------------------------------------------- STATIC text

