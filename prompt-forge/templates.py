# ---------------------------------------------------------------- LIVE blocks


def roster_block() -> str:
    rows = fleet_context.roster()
    if not rows:
        return "Node roster: UNAVAILABLE at generation time — run\n" \
               "`python3 /home/lumen/minerva/lumen_state.py current` after bootstrap.\n"
    lines = ["Node roster (live from lumen_state at generation time):"]
    for n in rows:
        ips = ", ".join(
            f"{k.replace('_ip', '')} {n[k]}" for k in ("tailscale_ip", "lan_ip") if k in n
        )
        lines.append(f"- {n['node']}" + (f" ({ips})" if ips else "") + f": {n.get('role', '')}")
    return "\n".join(lines) + "\n"


def autonomy_block() -> str:
    rows = fleet_context.autonomy()
    if not rows:
        return "Autonomy: state store unavailable — assume NO standing " \
               "authorization and ask before mutating anything.\n"
    lines = ["Autonomy & standing authorization (live from lumen_state, verbatim):"]
    for a in rows:
        lines.append(f"- fleet.{a['predicate']} (since {a['since']}): {a['value']}")
    return "\n".join(lines) + "\n"


def services_block() -> str:
    rows = fleet_context.services()
    if not rows:
        return ""
    hosts = ", ".join(s["hostname"].replace(".lumennode.uk", "") for s in rows)
    return f"Public services (*.lumennode.uk, live inventory): {hosts}\n"


def continuation_block(slug: str) -> str:
    ctx = fleet_context.project_context(slug)
    if not ctx.get("found"):
        return (f"Continuation requested for project '{slug}' but no directory at "
                f"/home/lumen/projects/{slug} — treat as a fresh start and create it.\n")
    parts = [f"Prior project context for '{slug}' (live from {ctx['path']}):"]
    if ctx.get("files"):
        parts.append("Files present: " + ", ".join(ctx["files"]))
    if ctx.get("status_md"):
        parts.append("--- STATUS.md ---\n" + ctx["status_md"].strip())
    if ctx.get("rules_yaml"):
        parts.append("--- .fworker-rules.yaml (project safety rules, binding) ---\n"
                     + ctx["rules_yaml"].strip())
    if ctx.get("state"):
        parts.append("--- lumen_state facts ---\n" + ctx["state"])
    return "\n".join(parts) + "\n"


# ---------------------------------------------------------------- assembly


def slugify(description: str) -> str:
    words = [w.lower() for w in description.split() if w.isalnum()][:4]
    return "-".join(words) or "new-project"


def assemble(
    description: str,
    category: str = "project",
    resources: str = "",
    filters: list[str] | None = None,
    answers: list[dict] | None = None,
    framing: str | None = None,
    project_slug: str = "",
    assumptions: list[str] | None = None,
) -> str:
    filters = [f for f in (filters or []) if f in FILTER_RULES or f == "continuation"]
    category = category if category in CATEGORIES else "project"
    slug = project_slug.strip() or slugify(description)
    now = time.strftime("%Y-%m-%d %H:%M UTC", time.gmtime())

    s: list[str] = []
    s.append(f"# {description.strip()}\n")
    s.append(f"(Prompt Forge, {now}. Category: {category}. "
             f"Fleet sections below were measured live, not recalled.)\n")
    s.append("## Fleet\n" + FLEET_IDENTITY)
    s.append("## Bootstrap\n" + BOOTSTRAP.format(slug=slug))
    s.append("## Nodes\n" + roster_block())
    s.append("## Autonomy\n" + autonomy_block())
    svc = services_block()
    if svc:
        s.append("## Services\n" + svc)

    rules = CATEGORY_RULES[category]
    for f in filters:
        rules += ("\n" if rules else "") + FILTER_RULES.get(f, "")
    if rules:
        s.append("## Rules\n" + rules)

    proj: list[str] = []
    if resources.strip():
        proj.append("Starting reading list (from Frank, read before acting):\n"
                    + resources.strip())
    if answers:
        qa = "\n".join(f"- Q: {a.get('q', '')}\n  A: {a.get('a', '')}"
                       for a in answers if a.get("a", "").strip())
        if qa:
            proj.append("Clarified up front:\n" + qa)
    if assumptions:
        proj.append("Assumptions made by the generator (challenge if wrong):\n"
                    + "\n".join(f"- {a}" for a in assumptions))
    if framing:
        proj.append("Briefing (drafted by the generator's model — verify "
                    "anything load-bearing):\n" + framing.strip())
    if proj:
        s.append("## Project\n" + "\n\n".join(proj) + "\n")

    if "continuation" in filters:
        s.append("## Prior context\n" + continuation_block(slug))

    s.append("## Lifecycle\n" + LIFECYCLE)
    s.append("Start now: restate the objective in one line, run the bootstrap, "
             "then begin with the first concrete step.")
    return "\n".join(s)
