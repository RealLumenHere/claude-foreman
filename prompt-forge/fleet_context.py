#!/usr/bin/env python3
"""fleet_context.py — deterministic fleet-context builders for Prompt Forge (wq#957).

Option B of decisions/PROMPT_FORGE_DESIGN.md: every fact that can be measured is
measured at request time — node roster, autonomy grants, service hostnames, project
state — never generated by an LLM. A model that recites the roster from memory gets
IPs wrong and resurrects retired nodes; this module exists so the generated prompt
is correct by construction.

Stdlib-only (repo convention, see dispatcher/dashboard.py). All sources are
read-only:

    lumen_state.py current            node roster, autonomy level/window
    sentinel/ui_inventory.json        public service hostnames (wq#770 discovery)
    projects/<slug>/                  continuation context (STATUS.md, rules file)

Every reader degrades to a labeled placeholder instead of raising: a generator
that refuses to emit a prompt because one source is down would fail Frank exactly
when the fleet is mid-incident and he most needs a well-briefed session.
"""

from __future__ import annotations

import json
import re
import subprocess
import time
from pathlib import Path

LUMEN_STATE = Path("/home/lumen/minerva/lumen_state.py")
UI_INVENTORY = Path("/home/lumen/sentinel/ui_inventory.json")
PROJECTS_DIR = Path("/home/lumen/projects")

STATE_TIMEOUT_S = 20
CACHE_TTL_S = 60

# subject.predicate = value  (since YYYY-MM-DD)
_STATE_LINE = re.compile(
    r"^\s*(?P<subject>[\w-]+)\.(?P<predicate>[\w-]+)\s*= (?P<value>.*?)\s*"
    r"\(since (?P<since>\d{4}-\d{2}-\d{2})\)\s*$"
)

_cache: dict[str, tuple[float, object]] = {}


def _cached(key: str, builder):
    now = time.monotonic()
    hit = _cache.get(key)
    if hit and now - hit[0] < CACHE_TTL_S:
        return hit[1]
    value = builder()
    _cache[key] = (now, value)
    return value


def _run_state(*args: str) -> str:
    try:
        proc = subprocess.run(
            ["python3", str(LUMEN_STATE), "current", *args],
            capture_output=True, text=True, timeout=STATE_TIMEOUT_S,
        )
        return proc.stdout if proc.returncode == 0 else ""
    except (OSError, subprocess.TimeoutExpired):
        return ""


def parse_state_lines(text: str) -> list[dict]:
    facts = []
    for line in text.splitlines():
        m = _STATE_LINE.match(line)
        if m:
            facts.append(m.groupdict())
    return facts


def state_facts() -> list[dict]:
    return _cached("state", lambda: parse_state_lines(_run_state()))


def _first_sentence(text: str, limit: int = 220) -> str:
    cut = text.split(". ")[0]
    return (cut[: limit - 1] + "…") if len(cut) > limit else cut


def roster() -> list[dict]:
    """Nodes = state subjects that declare a .role; IPs attached when present."""
    def build():
        nodes: dict[str, dict] = {}
        for f in state_facts():
            if f["predicate"] not in ("role", "tailscale_ip", "lan_ip"):
                continue
            node = nodes.setdefault(f["subject"], {"node": f["subject"]})
            if f["predicate"] == "role":
                node["role"] = _first_sentence(f["value"])
            else:
                node[f["predicate"]] = f["value"]
        return sorted(
            (n for n in nodes.values() if "role" in n),
            key=lambda n: n["node"],
        )
    return _cached("roster", build)


def autonomy() -> list[dict]:
    """Every current fleet.* autonomy/authorization grant, verbatim."""
    def build():
        return [
            {"predicate": f["predicate"], "value": f["value"], "since": f["since"]}
            for f in state_facts()
            if f["subject"] == "fleet" and (
                "autonomy" in f["predicate"] or "auth" in f["predicate"]
            )
        ]
    return _cached("autonomy", build)


def services() -> list[dict]:
    """Public hostnames from the wq#770 inventory (measured, not remembered)."""
    def build():
        try:
            inv = json.loads(UI_INVENTORY.read_text())
        except (OSError, ValueError):
            return []
        out = []
        for h in inv.get("ingress", []):
            if isinstance(h, dict) and h.get("hostname") \
                    and not h.get("retired") and not h.get("infra"):
                out.append({"hostname": h["hostname"]})
        return sorted(out, key=lambda s: s["hostname"])
    return _cached("services", build)


_SLUG_RE = re.compile(r"^[\w-]{1,64}$")


def project_context(slug: str) -> dict:
    """Continuation context for an existing project: directory scan + state.

    Answer to design open question 2: project directory + lumen_state, both
    live. The episode store is deliberately not read here — episodes are
    session-grained and huge; the per-project STATUS.md is the curated summary
    the fleet already maintains for exactly this purpose.
    """
    if not _SLUG_RE.match(slug or ""):
        return {"slug": slug, "found": False}
    root = PROJECTS_DIR / slug
    if not root.is_dir():
        return {"slug": slug, "found": False}
    ctx: dict = {"slug": slug, "found": True, "path": str(root)}

    status = root / "STATUS.md"
    if status.is_file():
        ctx["status_md"] = status.read_text(errors="replace")[:8000]

    rules = root / ".fworker-rules.yaml"
    if rules.is_file():
        ctx["rules_yaml"] = rules.read_text(errors="replace")[:4000]

    try:
        ctx["files"] = sorted(
            p.name for p in root.iterdir() if not p.name.startswith(".")
        )[:60]
    except OSError:
        ctx["files"] = []

    state = _run_state(slug)
    if state.strip():
        ctx["state"] = state.strip()[:6000]
    return ctx


def known_projects() -> list[str]:
    """Project slugs that look like real projects (have a STATUS.md or *.md)."""
    def build():
        out = []
        try:
            for p in PROJECTS_DIR.iterdir():
                if p.is_dir() and not re.fullmatch(r"[0-9a-f]{8}", p.name):
                    if any(c.suffix == ".md" for c in p.iterdir()):
                        out.append(p.name)
        except OSError:
            pass
        return sorted(out)
    return _cached("projects", build)


def compact_summary() -> str:
    """Small (~1-2 KB) fleet digest for the clarifying-questions LLM call.

    Answer to design open question 5: the question model gets the roster
    (names + one-line roles, no IPs), the autonomy level headline, and the
    known-project list — enough to recognize domains and continuations,
    small enough to keep the call cheap.
    """
    lines = ["Fleet nodes (name: role):"]
    for n in roster():
        lines.append(f"- {n['node']}: {n.get('role', '?')[:100]}")
    for a in autonomy():
        if a["predicate"] == "autonomy_level":
            lines.append(f"Autonomy: {a['value'][:200]}")
    kp = known_projects()
    if kp:
        lines.append("Existing projects: " + ", ".join(kp[:40]))
    return "\n".join(lines)


def snapshot() -> dict:
    return {
        "roster": roster(),
        "autonomy": autonomy(),
        "services": services(),
        "projects": known_projects(),
        "generated_at": time.strftime("%Y-%m-%d %H:%M:%S UTC", time.gmtime()),
    }
