#!/usr/bin/env bash
# wq#858 / wq#4899 — weekly Trivy CVE scan on Lumen. This bundle is the SINGLE SOURCE for
# the scan that is actually live:
#   scan.sh                     -> /home/lumen/services/trivy-weekly/scan.sh   (User=lumen)
#   lumen-trivy-weekly.service  -> /etc/systemd/system/                        (Type=oneshot)
#   lumen-trivy-weekly.timer    -> /etc/systemd/system/                        (Sun 09:00 UTC)
# All three are byte-for-byte the files that ran the valid weekly reports (2026-11-01,
# -05, -08, -15: 64-77 MB JSON, empty .json.err). SHA256SUMS pins them; --verify checks
# pin == bundle copy == live, so neither an un-repinned edit here nor a hand edit on the
# box can pass.
#
# Retired by wq#4899: the never-deployed root variant (trivy-scan.sh/.service/.timer +
# trivy_report.py, binary in /usr/local/bin, reports in /home/lumen/maint/trivy). See
# README.md. Not shipped here, and owned elsewhere:
#   - the trivy binary itself (/home/lumen/bin/trivy, v0.74.0) — checked, not installed;
#   - the dead-man drop-in lumen-trivy-weekly.service.d/99-cron-stamp.conf, generated by
#     lumen-cron-stamp-dropin-gen (wq#1658) for cron_deadman (wq#1184) — checked, not
#     written, so the generator stays its only author.
#
# Install: run as root via `lumen-run --root` on Lumen (repo convention; the BUILD-lane
# sandbox denies root, so it can stage this bundle but not run the install half).
set -euo pipefail

SRC="$(cd "$(dirname "$0")" && pwd)"
UNITS="lumen-trivy-weekly.service lumen-trivy-weekly.timer"
SYS=/etc/systemd/system
SCAN_DIR=/home/lumen/services/trivy-weekly
SCAN_DST="$SCAN_DIR/scan.sh"
DROPIN="$SYS/lumen-trivy-weekly.service.d/99-cron-stamp.conf"
TRIVY=/home/lumen/bin/trivy
RETIRED_UNITS="trivy-scan.service trivy-scan.timer"
RETIRED_DIR=/home/lumen/services/trivy-scan

# wq#1696 deploy-verify contract (ops/VERIFY_CONTRACT.md). Read-only; before any install step.
if [ "${1:-}" = --verify ]; then
  . "$SRC/../_verify.sh"
  # Test-only target overrides (ops/tests/test_wq4899_trivy_bundle.py); --verify only,
  # the install half below never reads them.
  SYS="${WQ4899_SYS:-$SYS}"
  SCAN_DST="${WQ4899_SCAN_DIR:-$SCAN_DIR}/scan.sh"
  DROPIN="$SYS/lumen-trivy-weekly.service.d/99-cron-stamp.conf"
  TRIVY="${WQ4899_TRIVY:-$TRIVY}"
  RETIRED_DIR="${WQ4899_RETIRED_DIR:-$RETIRED_DIR}"

  # vsha NAME DST — SHA256SUMS pin == bundle copy == live target.
  vsha() {
    local name="$1" dst="$2" pin have live
    pin="$(awk -v n="$name" '$2 == n { print $1 }' "$SRC/SHA256SUMS" 2>/dev/null)"
    [ -n "$pin" ] || { echo "ERR no pin for $name in $SRC/SHA256SUMS"; _V_ERR=1; return; }
    [ -r "$SRC/$name" ] || { echo "ERR source unreadable: $SRC/$name"; _V_ERR=1; return; }
    have="$(sha256sum < "$SRC/$name" | cut -d' ' -f1)"
    if [ "$have" != "$pin" ]; then
      _vmiss "bundle $name sha256 $have != pinned $pin (edited without re-pinning SHA256SUMS)"
      return
    fi
    if [ ! -e "$dst" ]; then _vmiss "absent: $dst"; return; fi
    [ -r "$dst" ] || { echo "ERR target unreadable: $dst"; _V_ERR=1; return; }
    live="$(sha256sum < "$dst" | cut -d' ' -f1)"
    [ "$live" = "$pin" ] || _vmiss "sha256 differs: $dst ($live, pinned $pin from $name)"
  }

  vsha scan.sh                    "$SCAN_DST"
  vsha lumen-trivy-weekly.service "$SYS/lumen-trivy-weekly.service"
  vsha lumen-trivy-weekly.timer   "$SYS/lumen-trivy-weekly.timer"
  [ ! -e "$SCAN_DST" ] || [ -x "$SCAN_DST" ] || _vmiss "not executable: $SCAN_DST"

  venabled         lumen-trivy-weekly.timer
  vactive          lumen-trivy-weekly.timer
  vtimer_scheduled lumen-trivy-weekly.timer

  # Dead-man: the oneshot only reaches ExecStartPost on success, and scan.sh exits 1 when
  # the JSON report is missing/<2KB/unparseable (wq#2858), so a failed scan leaves the
  # stamp stale and cron_deadman pages. Losing the drop-in would silence that.
  vcontains "$DROPIN" '^ExecStartPost=-?/home/lumen/bin/lumen-cron-stamp %n$'

  # The callee: scan.sh relies on these rootfs flags; ask the installed binary.
  if [ ! -x "$TRIVY" ]; then
    _vmiss "absent/not executable: $TRIVY (scan.sh's TRIVY=)"
  else
    rhelp="$("$TRIVY" rootfs --help 2>/dev/null || true)"
    for f in --skip-dirs --scanners --timeout; do
      printf '%s\n' "$rhelp" | grep -q -- "$f" || _vmiss "$TRIVY rootfs --help lacks $f"
    done
  fi

  # Retired root variant must stay retired: a second weekly scanner is the failure mode.
  for u in $RETIRED_UNITS; do
    [ ! -e "$SYS/$u" ] || _vmiss "retired unit present: $SYS/$u (lumen-trivy-weekly owns this scan)"
  done
  [ ! -e "$RETIRED_DIR" ] || _vmiss "retired payload dir present: $RETIRED_DIR"
  vdone
fi

if [ "$(id -u)" -ne 0 ]; then
  echo "refuse: install needs root (units in $SYS). Run via lumen-run --root; --verify needs none." >&2
  exit 2
fi

echo "== bundle integrity (SHA256SUMS) =="
( cd "$SRC" && sha256sum -c --strict SHA256SUMS )

[ -x "$TRIVY" ] || { echo "refuse: $TRIVY missing; this bundle does not install the binary" >&2; exit 2; }

echo "== scan script (owner lumen) =="
install -d -o lumen -g lumen -m 0755 "$SCAN_DIR" "$SCAN_DIR/reports"
install -o lumen -g lumen -m 0755 "$SRC/scan.sh" "$SCAN_DST"

echo "== units =="
for u in $UNITS; do
  install -o root -g root -m 0644 "$SRC/$u" "$SYS/$u"
done

echo "== retire root variant leftovers (never deployed; no-op unless someone ran the old bundle) =="
for u in $RETIRED_UNITS; do
  if [ -e "$SYS/$u" ]; then
    systemctl disable --now "$u" || true
    rm -f "$SYS/$u"
  fi
done
rm -rf "$RETIRED_DIR"

systemctl daemon-reload
systemctl enable --now lumen-trivy-weekly.timer

if [ ! -e "$DROPIN" ]; then
  echo "NOTE: dead-man drop-in missing: $DROPIN" >&2
  echo "      run: /home/lumen/bin/lumen-cron-stamp-dropin-gen plan  (then apply, as root)" >&2
fi

# wq#3579: bless exactly this bundle's units, last install step. Never `unit-drift snapshot`.
/home/lumen/bin/unit-drift accept --ticket wq#4899 $UNITS

echo "== verify =="
exec bash "$SRC/install.sh" --verify
