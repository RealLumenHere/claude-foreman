#!/usr/bin/env bash
# wq#5139: put the local-scope serial-maksoor MCP registration (project /data/lumen/archive/re) behind
# lumen_mcp_guard. It was a raw streamable-HTTP entry (http://100.81.204.74:8400/mcp, qarnet serial-mcp
# 0.9.3 on Maksoor, wq#4513): 25 tools, no allowlist, no masking, and no energize gate in interactive
# sessions (action_gate.py runs only inside foreman workers).
#
#   install.sh                 generate the launcher, install bridge + pins, re-register serial-maksoor
#   install.sh --verify        read-only deploy check (wq#1696 contract)
#   install.sh --print-launcher   print the launcher this script would write (read-only)
#   install.sh --gen-pins      list the guarded surface WITHOUT pins and print a pins doc (review first)
#
# Chain: Claude Code -> launch.sh -> lumen_mcp_guard (allowlist serial-allow.txt, pins, mask-secrets,
# max-result-bytes, untrusted-output, audit) -> http_stdio_bridge.py (energize-confirm gate, strips
# confirm_token) -> serial-mcp over HTTP on Maksoor.
set -euo pipefail
SRC="$(cd "$(dirname "$0")" && pwd)"

ROOT=/home/lumen/.local/share/mcp
GDIR=$ROOT/_guard
GPY=$GDIR/venv/bin/python
GUARD=$GDIR/lumen_mcp_guard.py
CLAUDE=/home/lumen/.npm-global/bin/claude
MASKER=/home/lumen/bin/mask-secrets
URL=http://100.81.204.74:8400/mcp
PROJECT=/data/lumen/archive/re
NAME=serial-maksoor
D=$ROOT/serial-maksoor
LAUNCHER=$D/launch.sh
BRIDGE=$D/http_stdio_bridge.py
ENERGIZE=$D/energize_confirm.py
ENERGIZE_SRC="$SRC/../../harness/energize_confirm.py"
PINS=$D/pins.json
ALLOW="$(grep -v '^#' "$SRC/serial-allow.txt" | grep . | paste -sd,)"

emit_launcher() {
cat <<EOF
#!/usr/bin/env bash
# GENERATED by ops/wq5139-serial-maksoor-guard/install.sh: do not hand-edit (install.sh --verify compares it).
# serial-maksoor (serial-mcp on Maksoor, HTTP) behind lumen_mcp_guard + energize-confirm bridge (wq#5139).
set -euo pipefail
export PYTHONWARNINGS=ignore
unset PYTHONPATH
exec $GPY -I $GUARD --name $NAME --call-timeout 120 \\
  --allow $ALLOW \\
  --mask-output $MASKER \\
  --max-result-bytes 524288 --untrusted-output \\
  --pins $PINS \\
  -- $GPY -I $BRIDGE $URL
EOF
}

n_allow() { printf '%s\n' "$ALLOW" | tr ',' '\n' | grep -c .; }

if [ "${1:-}" = --print-launcher ]; then emit_launcher; exit 0; fi

if [ "${1:-}" = --gen-pins ]; then
  tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
  cp "$SRC/http_stdio_bridge.py" "$ENERGIZE_SRC" "$tmp/"
  emit_launcher | grep -v -- '--pins ' | sed "s#$BRIDGE#$tmp/http_stdio_bridge.py#" > "$tmp/l.sh"
  env -u PYTHONPATH "$GPY" -I "$SRC/gen_pins.py" "$NAME@guarded" -- bash "$tmp/l.sh"
  exit 0
fi

if [ "${1:-}" = --verify ]; then
  . "$SRC/../_verify.sh"
  vfile "$SRC/../wq4514-mcp-install-batch/lumen_mcp_guard.py" "$GUARD"
  [ -x "$MASKER" ] || _vmiss "masker missing or not executable: $MASKER"
  vfile "$SRC/http_stdio_bridge.py" "$BRIDGE"
  vfile "$ENERGIZE_SRC" "$ENERGIZE"
  vfile "$SRC/serial-pins.json" "$PINS"
  if [ -e "$LAUNCHER" ]; then
    cmp -s <(emit_launcher) "$LAUNCHER" || _vmiss "differs from generator: $LAUNCHER"
  else
    _vmiss "absent: $LAUNCHER"
  fi
  reg="$(cd "$PROJECT" && "$CLAUDE" mcp get "$NAME" 2>/dev/null || true)"
  case "$reg" in *"$LAUNCHER"*) ;; *) _vmiss "claude MCP '$NAME' (cwd $PROJECT) not registered to $LAUNCHER";; esac
  case "$reg" in *"$URL"*) _vmiss "claude MCP '$NAME' still points at the raw HTTP URL $URL";; esac
  # Drift + liveness: needs Maksoor up. Unreachable backend is a MISS (the server is unusable either way).
  env -u PYTHONPATH timeout 60 "$GPY" -I "$GUARD" --list-backend --allow "$ALLOW" -- "$GPY" -I "$BRIDGE" "$URL" >/dev/null 2>&1 \
    || _vmiss "guard --list-backend: allowlisted tool missing upstream, or Maksoor serial-mcp unreachable"
  out="$(env -u PYTHONPATH timeout 60 "$GPY" -I "$GDIR/mcp_smoke.py" -- "$LAUNCHER" 2>/dev/null || true)"
  n="$(printf '%s\n' "$out" | sed -n 's/^tools\/list: \([0-9]*\) tools.*/\1/p')"
  [ "$n" = "$(n_allow)" ] || _vmiss "launcher $LAUNCHER lists '${n:-nothing}' tools, expected $(n_allow)"
  vdone
fi

[ -r "$GUARD" ] && [ -x "$GPY" ] || { echo "ERR shared guard not installed: run ops/wq4514-mcp-install-batch/install.sh first" >&2; exit 1; }
cmp -s "$SRC/../wq4514-mcp-install-batch/lumen_mcp_guard.py" "$GUARD" \
  || { echo "ERR $GUARD is not this branch's guard: run ops/wq4514-mcp-install-batch/install.sh first" >&2; exit 1; }
[ -x "$MASKER" ] || { echo "ERR $MASKER missing: refusing to expose serial output unmasked" >&2; exit 1; }
[ -r "$ENERGIZE_SRC" ] || { echo "ERR $ENERGIZE_SRC missing" >&2; exit 1; }
[ -r "$SRC/serial-pins.json" ] || { echo "ERR serial-pins.json missing: run --gen-pins, review, commit" >&2; exit 1; }
[ -d "$PROJECT" ] || { echo "ERR project dir missing: $PROJECT" >&2; exit 1; }

mkdir -p "$D"; chmod 700 "$D"
install -m 0644 "$SRC/http_stdio_bridge.py" "$BRIDGE"
install -m 0644 "$ENERGIZE_SRC" "$ENERGIZE"
install -m 0644 "$SRC/serial-pins.json" "$PINS"
emit_launcher > "$LAUNCHER"; chmod 0755 "$LAUNCHER"
mkdir -p /home/lumen/backups
cp -a /home/lumen/.claude.json "/home/lumen/backups/claude.json.pre-wq5139.$(date +%Y%m%d_%H%M%S)"
(cd "$PROJECT" && { "$CLAUDE" mcp remove -s local "$NAME" >/dev/null 2>&1 || true; } \
  && "$CLAUDE" mcp add-json -s local "$NAME" "{\"type\":\"stdio\",\"command\":\"$LAUNCHER\",\"args\":[],\"env\":{}}" >/dev/null)
exec bash "$SRC/install.sh" --verify
