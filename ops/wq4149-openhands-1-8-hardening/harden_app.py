#!/usr/bin/env python3
"""wq#4149 items 2 + 3 (app-container half): resource-limit the `openhands`
app container and fix root-owned workspace files it has already left behind.
Privileged lane only — docker is denied to BUILD workers (confirmed live,
`docker ps` -> permission denied, same wall wq#4007/wq#4111/wq#4018 hit; see
research/OPENHANDS_1_8_READINESS.md §4). Same posture as
ops/wq4111-openhands-litellm-production/configure_and_run_task.py: written
here, run from a container-capable operator lane.

Scope, deliberately narrow:
  1. Add `mem_limit`/`cpus` to the `openhands` app service in the compose
     override (NOT the agent-server sandbox containers — those are created
     per-task by the app itself, not by this compose file; limiting them is
     item 3's other half, needs the app's own sandbox-resource config knob,
     which this lane cannot read from the image — left for a privileged lane
     to confirm against the installed agent-server's actual config schema
     rather than guessed here).
  2. `chown -R` the `/home/lumen/.openhands` workspace subtree back to a
     non-root UID after the fact (the harness defect noted in wq#4007 §6 item
     7: root-run agents leave root-owned files). This does NOT make the
     container itself run as non-root going forward — that needs a `user:`
     directive in the compose plus confirming the image supports a non-root
     UID without breaking docker.sock access, which this lane cannot test
     without docker and is left open.

--dry-run prints the override it would write and the chown command it would
run, and changes nothing.
"""
import argparse
import os
import subprocess
import sys

COMPOSE_DIR = "/home/lumen/containers/openhands"
OVERRIDE_PATH = os.path.join(COMPOSE_DIR, "docker-compose.override.yml")
WORKSPACE_DIR = "/home/lumen/.openhands"
APP_MEM_LIMIT = "2g"
APP_CPUS = "2.0"
# Non-root UID to chown the workspace to. Pick an existing, unprivileged
# account on Lumen rather than inventing a UID — the operator running this
# script must confirm this is correct for this host before using it.
TARGET_UID_GID = "lumen:lumen"

OVERRIDE_YAML = f"""# wq#4149: resource limits for the openhands app container.
# Generated by ops/wq4149-openhands-1-8-hardening/harden_app.py — do not hand-edit;
# re-run the script to change the limits.
services:
  openhands:
    mem_limit: {APP_MEM_LIMIT}
    cpus: "{APP_CPUS}"
"""


def run(cmd, **kw):
    print(f"+ {' '.join(cmd)}")
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def write_override(dry_run):
    if dry_run:
        print(f"--dry-run: would write {OVERRIDE_PATH}:\n{OVERRIDE_YAML}")
        return
    with open(OVERRIDE_PATH, "w") as fh:
        fh.write(OVERRIDE_YAML)
    print(f"wrote {OVERRIDE_PATH}")


def recreate(dry_run):
    cmd = ["docker", "compose",
           "-f", os.path.join(COMPOSE_DIR, "docker-compose.yml"),
           "-f", OVERRIDE_PATH,
           "up", "-d", "--force-recreate", "openhands"]
    if dry_run:
        print(f"--dry-run: would run: {' '.join(cmd)}")
        return
    r = run(cmd, cwd=COMPOSE_DIR)
    if r.returncode != 0:
        raise SystemExit(f"compose up failed: {r.stderr.strip()}")


def fix_ownership(dry_run):
    cmd = ["chown", "-R", TARGET_UID_GID, WORKSPACE_DIR]
    if dry_run:
        print(f"--dry-run: would run: {' '.join(cmd)}")
        return
    r = run(cmd)
    if r.returncode != 0:
        raise SystemExit(f"chown failed: {r.stderr.strip()}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--skip-chown", action="store_true",
                     help="apply only the compose resource limits, not the ownership fix")
    args = ap.parse_args()

    write_override(args.dry_run)
    recreate(args.dry_run)
    if not args.skip_chown:
        fix_ownership(args.dry_run)
    print("done" if not args.dry_run else "--dry-run: no changes made")
    return 0


if __name__ == "__main__":
    sys.exit(main())
