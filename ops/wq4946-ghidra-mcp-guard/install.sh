#!/usr/bin/env bash
# wq#4946 (audit F6, docs/security/mcp-audit-2026-11.md): put the local-scope ghidra-lumen MCP
# registration (project /data/lumen/archive/re) behind lumen_mcp_guard. It was registered straight
# to /opt/ghidra-mcp/bridge-stdio.sh: 222 tools, no allowlist.
#
#   install.sh           generate the guarded launcher and re-register ghidra-lumen to it
#   install.sh --verify  read-only deploy check (wq#1696 contract)
#   install.sh --print-launcher   print the launcher this script would write (read-only)
#
# The guard and its venv are the shared ones from ops/wq4514-mcp-install-batch (install that first).
# What the guard adds on top of the server's own controls (run-headless.sh: loopback, bearer token,
# scripts off, GHIDRA_MCP_FILE_ROOT=/home/lumen/re):
#   * fail-closed allowlist (ghidra-allow.txt, 202 of 222). Hidden, see RUNBOOK.md for why each:
#     script execution, instance switching, tool-catalog meta tools, host-path writers
#     (export/archive/restore/create_project/import_program/delete_file), off-host writers
#     (checkin_program, archive_ingest_*), suggest_field_names. New upstream tools stay hidden;
#   * the three host-path readers that stay (load_program, import_file, open_project) are pinned
#     under $RE_ROOT by the guard too: the bridge talks to whatever listens on :8089, and a server
#     started outside run-headless.sh has no FILE_ROOT;
#   * --pins ghidra-pins.json (wq#4941): each exposed tool's definition must hash to its 2026-11-12
#     security-gate baseline, or it is hidden and refused (DRIFT row);
#   * output through mask-secrets, resources/prompts hidden, audit log of tool names + arg keys.
set -euo pipefail
SRC="$(cd "$(dirname "$0")" && pwd)"

ROOT=/home/lumen/.local/share/mcp
GDIR=$ROOT/_guard
GPY=$GDIR/venv/bin/python
GUARD=$GDIR/lumen_mcp_guard.py
CLAUDE=/home/lumen/.npm-global/bin/claude
MASKER=/home/lumen/bin/mask-secrets
BRIDGE=/opt/ghidra-mcp/bridge-stdio.sh
PROJECT=/data/lumen/archive/re
RE_ROOT=/home/lumen/re
NAME=ghidra-lumen
D=$ROOT/ghidra-lumen
LAUNCHER=$D/launch.sh
PINS=$D/pins.json
GHIDRA_ALLOW="$(grep -v '^#' "$SRC/ghidra-allow.txt" | grep . | paste -sd,)"
PATH_ARGS=(load_program:file import_file:file_path open_project:path)

emit_launcher() {
cat <<EOF
#!/usr/bin/env bash
# GENERATED by ops/wq4946-ghidra-mcp-guard/install.sh: do not hand-edit (install.sh --verify compares it).
# ghidra-lumen (bethington ghidra-mcp bridge) behind lumen_mcp_guard (wq#4946).
# --no-lazy: every allowlisted tool is registered on connect; the lazy-load meta tools are hidden.
set -euo pipefail
export PYTHONWARNINGS=ignore
exec $GPY -I $GUARD --name $NAME \\
  --allow $GHIDRA_ALLOW \\
$(for a in "${PATH_ARGS[@]}"; do printf '  --path-arg %s=%s \\\n' "$a" "$RE_ROOT"; done)
  --mask-output $MASKER \\
  --pins $PINS \\
  --env GHIDRA_MCP_BRIDGE_ARGS=--no-lazy \\
  -- $BRIDGE
EOF
}

n_allow() { printf '%s\n' "$GHIDRA_ALLOW" | tr ',' '\n' | grep -c .; }

if [ "${1:-}" = --print-launcher ]; then emit_launcher; exit 0; fi

if [ "${1:-}" = --verify ]; then
  . "$SRC/../_verify.sh"
  vfile "$SRC/../wq4514-mcp-install-batch/lumen_mcp_guard.py" "$GUARD"
  [ -x "$MASKER" ] || _vmiss "masker missing or not executable: $MASKER"
  vfile "$SRC/ghidra-pins.json" "$PINS"
  if [ -e "$LAUNCHER" ]; then
    cmp -s <(emit_launcher) "$LAUNCHER" || _vmiss "differs from generator: $LAUNCHER"
  else
    _vmiss "absent: $LAUNCHER"
  fi
  reg="$(cd "$PROJECT" && "$CLAUDE" mcp get "$NAME" 2>/dev/null || true)"
  case "$reg" in *"$LAUNCHER"*) ;; *) _vmiss "claude MCP '$NAME' (cwd $PROJECT) not registered to $LAUNCHER";; esac
  case "$reg" in *"$BRIDGE"*) _vmiss "claude MCP '$NAME' still points at the raw bridge $BRIDGE";; esac
  # Drift: every allowlisted tool must still exist upstream (exit 1 = missing_upstream).
  # GHIDRA_MCP_AUTOSTART=0: the bridge lists its catalog without a running Ghidra.
  GHIDRA_MCP_AUTOSTART=0 timeout 120 "$GPY" -I "$GUARD" --list-backend --allow "$GHIDRA_ALLOW" \
    --env GHIDRA_MCP_BRIDGE_ARGS=--no-lazy -- "$BRIDGE" >/dev/null 2>&1 \
    || _vmiss "guard --list-backend: allowlisted tool missing upstream, or backend unqueryable"
  out="$(GHIDRA_MCP_AUTOSTART=0 timeout 120 "$GPY" -I "$GDIR/mcp_smoke.py" -- "$LAUNCHER" 2>/dev/null || true)"
  n="$(printf '%s\n' "$out" | sed -n 's/^tools\/list: \([0-9]*\) tools.*/\1/p')"
  [ "$n" = "$(n_allow)" ] || _vmiss "launcher $LAUNCHER lists '${n:-nothing}' tools, expected $(n_allow)"
  vdone
fi

[ -r "$GUARD" ] && [ -x "$GPY" ] || { echo "ERR shared guard not installed: run ops/wq4514-mcp-install-batch/install.sh first" >&2; exit 1; }
cmp -s "$SRC/../wq4514-mcp-install-batch/lumen_mcp_guard.py" "$GUARD" \
  || { echo "ERR $GUARD is not this branch's guard (needs --path-arg): run 'ops/wq4514-mcp-install-batch/install.sh' first" >&2; exit 1; }
[ -x "$MASKER" ] || { echo "ERR $MASKER missing: refusing to expose ghidra output unmasked" >&2; exit 1; }
[ -x "$BRIDGE" ] || { echo "ERR $BRIDGE missing" >&2; exit 1; }
[ -d "$PROJECT" ] || { echo "ERR project dir missing: $PROJECT" >&2; exit 1; }

mkdir -p "$D"; chmod 700 "$D"
install -m 0644 "$SRC/ghidra-pins.json" "$PINS"
emit_launcher > "$LAUNCHER"; chmod 0755 "$LAUNCHER"
mkdir -p /home/lumen/backups
cp -a /home/lumen/.claude.json "/home/lumen/backups/claude.json.pre-wq4946.$(date +%Y%m%d_%H%M%S)"
(cd "$PROJECT" && { "$CLAUDE" mcp remove -s local "$NAME" >/dev/null 2>&1 || true; } \
  && "$CLAUDE" mcp add-json -s local "$NAME" "{\"type\":\"stdio\",\"command\":\"$LAUNCHER\",\"args\":[],\"env\":{}}" >/dev/null)
exec "$0" --verify
