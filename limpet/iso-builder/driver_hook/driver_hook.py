#!/usr/bin/env python3
"""wq#3980 -- ISO driver-bundle hook (runner-agnostic).

Consumes the wq#3941 bundle (build_iso_drivers.py --write-bundle) and installs
it into an assembled chroot against the pinned kernel ABI (kernel.pin). Same
code serves build.sh stage7 (remaster chroot) and could be dropped into a
live-build config/hooks/ or mkosi postinst -- it only needs a chroot dir.

  plan              print the install plan (JSON); exit 4 if a DKMS module is unpinned
  install           place udev rules / hardware.d / docs / plan into --chroot
                    (--run-chroot additionally executes the in-chroot installer; needs root)
  verify-installed  wizard Phase 4 check against --root (default /)

Exit codes: 2 bad pin, 3 chroot kernel != pin, 4 unpinned/unsafe DKMS source, 5 verify failed.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
LIMPET = HERE.parent.parent
sys.path.insert(0, str(LIMPET / "hardware.d"))
import build_iso_drivers as bid  # noqa: E402

E_PIN, E_KERNEL, E_SOURCE, E_VERIFY = 2, 3, 4, 5
APT_NAME = re.compile(r"^[a-z0-9][a-z0-9+.\-]*$")
COMMIT = re.compile(r"^[0-9a-f]{40}$")
ABI = re.compile(r"^\d+\.\d+\.\d+-\d+-[a-z0-9]+$")
STAGE = "opt/limpet/driver-bundle"


class HookError(Exception):
    def __init__(self, code: int, msg: str):
        super().__init__(msg)
        self.code = code


def read_pin(path: pathlib.Path = HERE / "kernel.pin") -> dict:
    pin = {}
    for ln in path.read_text().splitlines():
        ln = ln.strip()
        if ln and not ln.startswith("#"):
            k, _, v = ln.partition("=")
            pin[k.strip()] = v.strip()
    for k in ("BASE_ISO_NAME", "BASE_ISO_SHA256", "KERNEL_ABI"):
        if not pin.get(k):
            raise HookError(E_PIN, f"kernel.pin missing {k}")
    if not ABI.match(pin["KERNEL_ABI"]):
        raise HookError(E_PIN, f"KERNEL_ABI {pin['KERNEL_ABI']!r} is not <ver>-<abi>-<flavour>")
    if not re.match(r"^[0-9a-f]{64}$", pin["BASE_ISO_SHA256"]):
        raise HookError(E_PIN, "BASE_ISO_SHA256 is not 64 hex chars")
    return pin


def read_sources(path: pathlib.Path = HERE / "dkms-sources.pin"):
    pins, skips = {}, {}
    for ln in path.read_text().splitlines():
        ln = ln.strip()
        if not ln or ln.startswith("#"):
            continue
        f = ln.split(None, 3)
        if f[0] == "pin" and len(f) == 4:
            _, mod, url, commit = f
            if not url.startswith("https://") or not COMMIT.match(commit):
                raise HookError(E_SOURCE, f"pin for {mod}: need https URL + 40-hex commit")
            pins[mod] = (url, commit)
        elif f[0] == "skip" and len(f) >= 3:
            skips[f[1]] = ln.split(None, 2)[2]
        else:
            raise HookError(E_SOURCE, f"unparseable pin line: {ln!r}")
    return pins, skips


def classify_firmware(ref: str):
    if ref.startswith("bundled:"):
        return "bundled", ref.split(":", 1)[1]
    if ref.startswith("proprietary:"):
        return "proprietary", ref.split(":", 1)[1]
    if not APT_NAME.match(ref):
        raise HookError(E_SOURCE, f"firmware ref {ref!r} is not a valid apt package name")
    return "apt", ref


def build_plan(devices, pin, pins, skips) -> dict:
    dkms = []
    for t in bid.dkms_targets(devices):
        mod = t.module.split()[0]
        if mod in skips:
            dkms.append({"module": mod, "status": "skipped", "reason": skips[mod]})
        elif mod in pins:
            url, commit = pins[mod]
            dkms.append({"module": mod, "status": "build", "url": url, "commit": commit})
        else:
            raise HookError(E_SOURCE, f"DKMS module {mod!r} has no pin/skip in dkms-sources.pin "
                            f"(catalog source: {t.source!r}) -- refusing to build unpinned code")
    fw = {"apt": set(), "bundled": set(), "proprietary": set()}
    for t in bid.firmware_targets(devices):
        kind, name = classify_firmware(t.package)
        fw[kind].add(name)
    return {"kernel_abi": pin["KERNEL_ABI"], "base_iso": pin["BASE_ISO_NAME"],
            "base_iso_sha256": pin["BASE_ISO_SHA256"], "dkms": dkms,
            "firmware": {k: sorted(v) for k, v in fw.items()},
            "note": "proprietary firmware is never auto-bundled (EULA); route via sideload"}


def chroot_script(plan: dict) -> str:
    abi = plan["kernel_abi"]
    builds = [d for d in plan["dkms"] if d["status"] == "build"]
    L = ["#!/bin/bash", "# generated by driver_hook.py (wq#3980); runs INSIDE the chroot",
         "set -euo pipefail", "export DEBIAN_FRONTEND=noninteractive"]
    apt = list(plan["firmware"]["apt"])
    if builds:
        apt += ["dkms", "build-essential", "git", f"linux-headers-{abi}"]
    if apt:
        L.append("apt-get install -y --no-install-recommends " + " ".join(sorted(set(apt))))
    for d in builds:
        src = f"/usr/src/{d['module']}-{d['commit'][:12]}"
        L += [f"git clone --no-checkout {d['url']} {src}",
              f"git -C {src} checkout --detach {d['commit']}",
              f'test "$(git -C {src} rev-parse HEAD)" = {d["commit"]}',
              f"N=$(sed -n 's/^PACKAGE_NAME=\"\\?\\([^\"]*\\)\"\\?.*/\\1/p' {src}/dkms.conf | head -1)",
              f"V=$(sed -n 's/^PACKAGE_VERSION=\"\\?\\([^\"]*\\)\"\\?.*/\\1/p' {src}/dkms.conf | head -1)",
              f'dkms add {src}', f'dkms install -m "$N" -v "$V" -k {abi}']
    if builds:
        L.append(f"depmod -a {abi}")
    return "\n".join(L) + "\n"


def check_chroot_kernel(chroot: pathlib.Path, abi: str):
    mods = chroot / "usr/lib/modules"
    have = sorted(p.name for p in mods.iterdir() if p.is_dir()) if mods.is_dir() else []
    if have and abi not in have:
        raise HookError(E_KERNEL, f"chroot carries kernel(s) {have} but pin is {abi}; "
                        "DKMS/in-kernel claims were verified only for the pin")


def install(chroot: pathlib.Path, bundle: pathlib.Path, run_chroot: bool = False) -> dict:
    pin = read_pin()
    pins, skips = read_sources()
    devices = bid.load_catalog()
    plan = build_plan(devices, pin, pins, skips)
    check_chroot_kernel(chroot, pin["KERNEL_ABI"])
    for rel in ("etc/udev/rules.d", "etc/modprobe.d", "etc/limpet/hardware.d", "opt/limpet/docs", STAGE):
        (chroot / rel).mkdir(parents=True, exist_ok=True)
    shutil.copy2(bundle / bid.UDEV_RULES_FILENAME, chroot / "etc/udev/rules.d" / bid.UDEV_RULES_FILENAME)
    shutil.copy2(bundle / bid.MODPROBE_FILENAME, chroot / "etc/modprobe.d" / bid.MODPROBE_FILENAME)
    for toml in sorted(bid.CATALOG_DIR.glob("*.toml")):
        shutil.copy2(toml, chroot / "etc/limpet/hardware.d" / toml.name)
    for doc in ("prebake-plan.md", "PROPRIETARY-LIMITATIONS.md"):
        shutil.copy2(bundle / doc, chroot / "opt/limpet/docs" / doc)
    (chroot / STAGE / "driver-plan.json").write_text(json.dumps(plan, indent=2, sort_keys=True) + "\n")
    shutil.copy2(HERE / "kernel.pin", chroot / STAGE / "kernel.pin")
    script = chroot / STAGE / "install-drivers.sh"
    script.write_text(chroot_script(plan))
    script.chmod(0o755)
    if run_chroot:
        subprocess.run(["chroot", str(chroot), "/bin/bash", f"/{STAGE}/install-drivers.sh"], check=True)
    return plan


def verify_installed(root: pathlib.Path) -> dict:
    res = {"rules": (root / "etc/udev/rules.d" / bid.UDEV_RULES_FILENAME).is_file(),
           "hardware_d": len(list((root / "etc/limpet/hardware.d").glob("*.toml"))) if (root / "etc/limpet/hardware.d").is_dir() else 0,
           "plan": None}
    p = root / STAGE / "driver-plan.json"
    if p.is_file():
        res["plan"] = json.loads(p.read_text())["kernel_abi"]
    res["ok"] = bool(res["rules"] and res["hardware_d"] and res["plan"])
    return res


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("plan")
    i = sub.add_parser("install")
    i.add_argument("--chroot", type=pathlib.Path, required=True)
    i.add_argument("--bundle", type=pathlib.Path, required=True)
    i.add_argument("--run-chroot", action="store_true")
    v = sub.add_parser("verify-installed")
    v.add_argument("--root", type=pathlib.Path, default=pathlib.Path("/"))
    a = ap.parse_args(argv)
    try:
        if a.cmd == "plan":
            pins, skips = read_sources()
            print(json.dumps(build_plan(bid.load_catalog(), read_pin(), pins, skips), indent=2, sort_keys=True))
        elif a.cmd == "install":
            plan = install(a.chroot, a.bundle, a.run_chroot)
            print(f"driver_hook: installed for {plan['kernel_abi']}: "
                  f"dkms build={sum(d['status']=='build' for d in plan['dkms'])} "
                  f"skipped={sum(d['status']=='skipped' for d in plan['dkms'])} "
                  f"apt-fw={len(plan['firmware']['apt'])} proprietary-skipped={len(plan['firmware']['proprietary'])}")
        else:
            r = verify_installed(a.root)
            print(json.dumps(r))
            return 0 if r["ok"] else E_VERIFY
    except HookError as e:
        print(f"driver_hook: FAIL ({e.code}): {e}", file=sys.stderr)
        return e.code
    return 0


if __name__ == "__main__":
    sys.exit(main())
