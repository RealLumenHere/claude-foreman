#!/usr/bin/env python3
"""Generate the Tool Reference page from the live tool surface.

Two sources of truth, merged into one page so the docs never drift from the
shipped appliance:

  * ``limpet/tool-catalog.json`` — the core/bundled tools the registry audits
    (``tools`` array, grouped by ``categories``).
  * ``plugins/*/limpet-plugin.toml`` — first-party plugin manifests (MCP
    wrappers over a CLI or device), the hot-swappable tier.

Run it from anywhere; paths are resolved relative to this file, not the cwd::

    python3 limpet/docs-site/gen_tool_reference.py          # write the page
    python3 limpet/docs-site/gen_tool_reference.py --check   # verify it is up to date (CI)

``--check`` exits non-zero when the committed page differs from what the current
catalog/manifests would produce, so a tool added to the catalog without
regenerating the docs fails the build instead of shipping a stale reference.
"""
from __future__ import annotations

import argparse
import json
import sys
import tomllib
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
LIMPET_DIR = SCRIPT_DIR.parent
REPO_ROOT = LIMPET_DIR.parent
CATALOG = LIMPET_DIR / "tool-catalog.json"
PLUGINS_DIR = REPO_ROOT / "plugins"
OUT = SCRIPT_DIR / "docs" / "tool-reference.md"

MARKER = (
    "<!-- GENERATED by limpet/docs-site/gen_tool_reference.py — do not edit by "
    "hand; run the script to refresh. -->"
)


def _fmt_list(values: list[str] | None) -> str:
    if not values:
        return "—"
    return ", ".join(f"`{v}`" for v in values)


def _slug(text: str) -> str:
    return "".join(c if c.isalnum() else "-" for c in text.lower()).strip("-")


def _load_catalog() -> dict:
    with CATALOG.open("rb") as fh:
        return json.load(fh)


def _load_manifests() -> list[dict]:
    manifests = []
    for toml_path in sorted(PLUGINS_DIR.glob("*/limpet-plugin.toml")):
        with toml_path.open("rb") as fh:
            data = tomllib.load(fh)
        plugin = data.get("plugin", {})
        if not plugin.get("name"):
            continue
        manifests.append({"data": data, "rel": toml_path.relative_to(REPO_ROOT)})
    return manifests


def _render_catalog(cat: dict, lines: list[str]) -> None:
    tools = cat.get("tools", [])
    categories = cat.get("categories", [])
    by_cat: dict[str, list[dict]] = {}
    for tool in tools:
        by_cat.setdefault(tool.get("category", "uncategorized"), []).append(tool)

    lines.append("## Core tools")
    lines.append("")
    lines.append(
        f"The appliance ships **{len(tools)} audited core tools** "
        f"(catalog `{cat.get('catalog_version', '?')}`, generated "
        f"{cat.get('generated', '?')}). These are the tools the registry "
        "health-checks on boot; see [Plugins](#plugins) below for the "
        "hot-swappable tier."
    )
    lines.append("")

    for category in categories:
        cid = category["id"]
        members = by_cat.get(cid, [])
        if not members:
            continue
        lines.append(f"### {category['title']}")
        lines.append("")
        if category.get("description"):
            lines.append(f"_{category['description']}_")
            lines.append("")
        for tool in sorted(members, key=lambda t: t["name"].lower()):
            _render_tool(tool, lines)

    # Any tool whose category is not in the declared list still gets rendered.
    stray = {t.get("category") for t in tools} - {c["id"] for c in categories}
    for cid in sorted(c for c in stray if c):
        lines.append(f"### {cid}")
        lines.append("")
        for tool in sorted(by_cat[cid], key=lambda t: t["name"].lower()):
            _render_tool(tool, lines)


def _render_tool(tool: dict, lines: list[str]) -> None:
    lines.append(f"#### {tool['name']}")
    lines.append("")
    if tool.get("description"):
        lines.append(tool["description"])
        lines.append("")
    rows = [
        ("Version", f"`{tool['version']}`" if tool.get("version") else "—"),
        ("Trust tier", f"`{tool.get('trust', '—')}`"),
        ("License", f"`{tool.get('license', '—')}`"),
        ("Capabilities", _fmt_list(tool.get("capabilities"))),
        ("Input formats", _fmt_list(tool.get("input_formats"))),
        ("Output formats", _fmt_list(tool.get("output_formats"))),
        ("Architectures", _fmt_list(tool.get("architectures"))),
    ]
    lines.append("| | |")
    lines.append("|---|---|")
    for label, value in rows:
        lines.append(f"| **{label}** | {value} |")
    lines.append("")
    if tool.get("health_check"):
        lines.append("Check it is installed and reachable:")
        lines.append("")
        lines.append("```sh")
        lines.append(tool["health_check"])
        lines.append("```")
        lines.append("")
    if tool.get("url"):
        lines.append(f"Upstream: <{tool['url']}>")
        lines.append("")


def _render_plugins(manifests: list[dict], lines: list[str]) -> None:
    lines.append("## Plugins")
    lines.append("")
    lines.append(
        f"**{len(manifests)} first-party plugins** ship a `limpet-plugin.toml` "
        "manifest. Each is a thin MCP wrapper over a CLI or a piece of hardware "
        "and can be enabled, disabled, or replaced at runtime "
        "(see [Plugin Development](plugin-development.md))."
    )
    lines.append("")
    for entry in sorted(manifests, key=lambda m: m["data"]["plugin"]["name"]):
        data = entry["data"]
        plugin = data["plugin"]
        caps = data.get("capabilities", {})
        hints = data.get("agent_hints", {})
        lines.append(f"### {plugin['name']}")
        lines.append("")
        if plugin.get("description"):
            lines.append(plugin["description"])
            lines.append("")
        rows = [
            ("Version", f"`{plugin.get('version', '—')}`"),
            ("Category", f"`{plugin.get('category', '—')}`"),
            ("License", f"`{plugin.get('license', '—')}`"),
            ("Manifest", f"`{entry['rel']}`"),
            ("Architectures", _fmt_list(caps.get("architectures"))),
            ("Input formats", _fmt_list(caps.get("input_formats"))),
            ("Output formats", _fmt_list(caps.get("output_formats"))),
        ]
        lines.append("| | |")
        lines.append("|---|---|")
        for label, value in rows:
            lines.append(f"| **{label}** | {value} |")
        lines.append("")
        if hints.get("when_to_use"):
            lines.append(f"**When to use:** {hints['when_to_use']}")
            lines.append("")
        if hints.get("when_not_to_use"):
            lines.append(f"**When not to use:** {hints['when_not_to_use']}")
            lines.append("")


def render() -> str:
    cat = _load_catalog()
    manifests = _load_manifests()
    lines: list[str] = [
        MARKER,
        "",
        "# Tool Reference",
        "",
        "Every tool Limpet can drive, grouped by category. This page is "
        "generated from the appliance's own tool catalog and plugin manifests "
        "by `limpet/docs-site/gen_tool_reference.py` — it is the same data the "
        "registry and the agent read, so it cannot drift from what the box "
        "actually ships.",
        "",
    ]
    _render_catalog(cat, lines)
    _render_plugins(manifests, lines)
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the committed page is stale (CI gate)",
    )
    args = parser.parse_args(argv)

    content = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            print(
                f"{OUT.relative_to(REPO_ROOT)} is stale — run "
                "`python3 limpet/docs-site/gen_tool_reference.py`",
                file=sys.stderr,
            )
            return 1
        print(f"{OUT.relative_to(REPO_ROOT)} is up to date")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content, encoding="utf-8")
    tool_count = len(_load_catalog().get("tools", []))
    print(f"wrote {OUT.relative_to(REPO_ROOT)} ({tool_count} tools, {len(_load_manifests())} plugins)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
