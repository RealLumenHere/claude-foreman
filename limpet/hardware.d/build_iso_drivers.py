"""ISO build helper for wq#3924/wq#3941: scans the hardware driver catalog
(limpet/hardware.d/*.toml) and emits what the Limpet ISO build needs to
pre-bake so every cataloged RE device works offline, out of the box --
no network needed at install time to `apt install` a DKMS module or
download a firmware blob.

Three outputs, all derived straight from the catalog (never hand-maintained
in parallel with it):
  - DKMS modules to pre-compile into the ISO (dkms=true entries)
  - firmware packages to bundle (firmware_blob=true entries with a named
    firmware_package)
  - a consolidated udev rules file for /etc/udev/rules.d/90-limpet-hardware.rules
    (udev_rule entries) and a proprietary/closed-source limitations doc
    (proprietary_notes entries)

load_catalog/dkms_targets/firmware_targets/udev_rules/proprietary_report are
pure: they read the catalog dir and return data. write_bundle is the one
function that touches the filesystem, and only ever writes into a
caller-given directory -- no subprocess calls, no compiling. Actually
pre-compiling a dkms_targets() module against a real kernel ABI, or copying
a firmware_targets() package into the ISO's package pool, is the ISO build
script's job (mkosi/live-build hook) once that pipeline exists; see
limpet/hardware.d/README.md for current status (no base image/pinned
target kernel yet, tracked wq#3941 follow-up).
"""
from __future__ import annotations

import argparse
import dataclasses
import pathlib
import tomllib

CATALOG_DIR = pathlib.Path(__file__).parent
UDEV_RULES_FILENAME = "90-limpet-hardware.rules"


@dataclasses.dataclass(frozen=True)
class DkmsTarget:
    device: str
    module: str
    source: str
    build_estimate_minutes: int


@dataclasses.dataclass(frozen=True)
class FirmwareTarget:
    device: str
    package: str
    note: str


def load_catalog(catalog_dir: pathlib.Path = CATALOG_DIR) -> list[dict]:
    """Every [[device]] table from every *.toml in catalog_dir, in filename order."""
    devices = []
    for toml_path in sorted(catalog_dir.glob("*.toml")):
        with toml_path.open("rb") as f:
            data = tomllib.load(f)
        devices.extend(data.get("device", []))
    return devices


def dkms_targets(devices: list[dict]) -> list[DkmsTarget]:
    return [
        DkmsTarget(
            device=d["name"],
            module=d["linux_driver"],
            source=d.get("dkms_source", ""),
            build_estimate_minutes=d.get("dkms_build_estimate_minutes", 0),
        )
        for d in devices
        if d.get("dkms")
    ]


def firmware_targets(devices: list[dict]) -> list[FirmwareTarget]:
    return [
        FirmwareTarget(
            device=d["name"],
            package=d["firmware_package"],
            note=d.get("firmware_note", ""),
        )
        for d in devices
        if d.get("firmware_blob") and d.get("firmware_package", "none") != "none"
    ]


def udev_rules(devices: list[dict]) -> str:
    """Consolidated udev rules text for /etc/udev/rules.d/90-limpet-hardware.rules,
    one block per device with a non-empty udev_rule. Devices whose udev_rule is ""
    (in-kernel drivers with no raw-USB-node permission need, e.g. network adapters)
    are skipped. Drops each device's own suggested standalone-file path comment
    (e.g. "# /etc/udev/rules.d/60-ch341a-programmer.rules") since every rule now
    ships consolidated in one file.
    """
    blocks = []
    for d in sorted(devices, key=lambda d: d["name"]):
        rule = d.get("udev_rule", "").strip()
        if not rule:
            continue
        body_lines = [
            ln for ln in rule.splitlines()
            if ln.strip() and not ln.strip().startswith("# /etc/udev/rules.d/")
        ]
        blocks.append(f"# {d['name']}\n" + "\n".join(body_lines))
    header = (
        f"# {UDEV_RULES_FILENAME}\n"
        "# Generated by limpet/hardware.d/build_iso_drivers.py from limpet/hardware.d/*.toml\n"
        "# (wq#3941). Do not hand-edit -- edit the device's udev_rule in its category\n"
        "# .toml and regenerate.\n"
    )
    return header + "\n\n".join(blocks) + "\n"


def proprietary_report(devices: list[dict]) -> str:
    """Consolidated proprietary/closed-source limitations doc: one section per
    device whose proprietary_notes is non-empty and isn't a plain "fully open"
    clearance, so a reader sees only the devices that actually carry a caveat.
    """
    lines = [
        "# Limpet hardware driver bundle -- proprietary/closed-source limitations (wq#3941)",
        "",
        "Generated from limpet/hardware.d/*.toml proprietary_notes fields. Devices with",
        "no caveat (fully open driver and firmware) are omitted.",
        "",
    ]
    for d in sorted(devices, key=lambda d: d["name"]):
        note = d.get("proprietary_notes", "").strip()
        if not note or note.lower().startswith("none."):
            continue
        lines.append(f"## {d['name']}")
        lines.append(note)
        lines.append("")
    return "\n".join(lines)


def write_bundle(devices: list[dict], bundle_dir: pathlib.Path) -> dict[str, pathlib.Path]:
    """Writes the three ISO-build-time artifacts derived from the catalog into
    bundle_dir: the consolidated udev rules file (installed to
    /etc/udev/rules.d/90-limpet-hardware.rules), the DKMS/firmware pre-bake plan,
    and the proprietary-limitations doc. The caller (the ISO build script) is
    responsible for copying udev_rules into the image and for actually running
    DKMS/firmware pre-bake against the image's target kernel.
    """
    bundle_dir.mkdir(parents=True, exist_ok=True)
    paths = {
        "udev_rules": bundle_dir / UDEV_RULES_FILENAME,
        "prebake_plan": bundle_dir / "prebake-plan.md",
        "proprietary_notes": bundle_dir / "PROPRIETARY-LIMITATIONS.md",
    }
    paths["udev_rules"].write_text(udev_rules(devices))
    paths["prebake_plan"].write_text(render_report(devices))
    paths["proprietary_notes"].write_text(proprietary_report(devices))
    return paths


def render_report(devices: list[dict]) -> str:
    dkms = dkms_targets(devices)
    fw = firmware_targets(devices)
    lines = ["# Limpet ISO hardware pre-bake plan (generated from limpet/hardware.d/*.toml)", ""]
    lines.append(f"## DKMS modules to pre-compile ({len(dkms)})")
    total_minutes = sum(t.build_estimate_minutes for t in dkms)
    for t in dkms:
        lines.append(f"- {t.module}  <- {t.device}  ({t.source})  ~{t.build_estimate_minutes} min")
    lines.append(f"  total estimated build time: ~{total_minutes} min")
    lines.append("")
    lines.append(f"## Firmware/package targets to bundle ({len(fw)})")
    for t in sorted(fw, key=lambda t: t.package):
        lines.append(f"- {t.package}  <- {t.device}")
        if t.note:
            lines.append(f"    {t.note}")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write-bundle",
        metavar="DIR",
        type=pathlib.Path,
        help="write the udev rules file, prebake plan, and proprietary-limitations "
        "doc into DIR instead of printing the plan (the ISO build script's hook "
        "point for this ticket)",
    )
    args = parser.parse_args()
    devices = load_catalog()
    if args.write_bundle:
        paths = write_bundle(devices, args.write_bundle)
        for label, path in paths.items():
            print(f"{label}: {path}")
    else:
        print(render_report(devices))


if __name__ == "__main__":
    main()
